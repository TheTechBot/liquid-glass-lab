#!/usr/bin/env node
// Generates platform token files from tokens.json.
// Usage: node design-system/tokens/build-tokens.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const t = JSON.parse(readFileSync(join(here, 'tokens.json'), 'utf8'));

const out = (rel, text) => {
  const p = join(root, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, text);
  console.log('wrote', rel);
};

// ---------- CSS ----------
const m = t.material;
const scheme = (s) => `
  --lg-regular-fill: ${m.regular[s].fill};
  --lg-regular-fill-pressed: ${m.regular[s].fillPressed};
  --lg-regular-fill-thick: ${m.regular[s].fillThick};
  --lg-regular-text: ${m.regular[s].text};
  --lg-regular-text-2: ${m.regular[s].textSecondary};
  --lg-regular-rim: ${m.regular[s].rim};
  --lg-regular-rim-dark: ${m.regular[s].rimDark};
  --lg-clear-fill: ${m.clear[s].fill};
  --lg-clear-fill-pressed: ${m.clear[s].fillPressed};
  --lg-clear-text: ${m.clear[s].text};
  --lg-clear-text-2: ${m.clear[s].textSecondary};
  --lg-clear-rim: ${m.clear[s].rim};
  --lg-clear-rim-dark: ${m.clear[s].rimDark};
  --lg-standard-fill: ${m.standard[s].fill};
  --lg-standard-text: ${m.standard[s].text};
  --lg-rt-fill: ${m.reducedTransparency[s].fill};
  --lg-ic-fill: ${m.increasedContrast[s].fill};
  --lg-ic-text: ${m.increasedContrast[s].text};
  --lg-ic-border: ${m.increasedContrast[s].border};`;

const px = (o) => Object.entries(o).filter(([, v]) => typeof v === 'number')
  .map(([k, v]) => `  --lg-${k}: ${v}px;`).join('\n');

const css = `/* GENERATED by build-tokens.mjs from tokens.json — do not edit by hand. */
/* Numeric values are project estimates, not Apple values (see research/unknowns-and-limitations.md). */
:root {
  color-scheme: light dark;
${scheme('light')}
  --lg-regular-blur: ${m.regular.blur}px;
  --lg-regular-saturate: ${m.regular.saturate};
  --lg-regular-brightness: ${m.regular.brightness};
  --lg-clear-blur: ${m.clear.blur}px;
  --lg-clear-saturate: ${m.clear.saturate};
  --lg-clear-dimming: ${m.clear.dimming.value};
  --lg-standard-blur: ${m.standard.blur}px;
  --lg-standard-saturate: ${m.standard.saturate};
  --lg-ic-border-width: ${m.increasedContrast.borderWidth}px;
  --lg-shadow-sm: ${t.elevation.sm};
  --lg-shadow-md: ${t.elevation.md};
  --lg-shadow-lg: ${t.elevation.lg};
${Object.entries(t.radius).map(([k, v]) => `  --lg-radius-${k}: ${v}px;`).join('\n')}
${Object.entries(t.spacing).map(([k, v]) => `  --lg-space-${k}: ${v}px;`).join('\n')}
${px(t.size).replace(/--lg-/g, '--lg-size-')}
  --lg-tint-accent: ${t.tint.accent};
  --lg-tint-accent-text: ${t.tint.accentText};
  --lg-tint-destructive: ${t.tint.destructive};
  --lg-tint-success: ${t.tint.success};
  --lg-spring: ${t.motion.springCss};
  --lg-ease-out: ${t.motion.easeOut};
  --lg-dur-fast: ${t.motion.durationFast}ms;
  --lg-dur-base: ${t.motion.durationBase}ms;
  --lg-dur-slow: ${t.motion.durationSlow}ms;
  --lg-press-scale: ${t.motion.pressScale};
  --lg-materialize-scale: ${t.motion.materializeFromScale};
}
@media (prefers-color-scheme: dark) {
  :root {${scheme('dark')}
  }
}
[data-lg-scheme="light"] {${scheme('light')}
}
[data-lg-scheme="dark"] {${scheme('dark')}
}
`;
out('implementations/web/src/tokens.css', css);

// ---------- TS (React + React Native) ----------
const ts = `// GENERATED by build-tokens.mjs from tokens.json — do not edit by hand.
// Numeric values are project estimates, not Apple values.
export const tokens = ${JSON.stringify(t, null, 2)} as const;
export type LiquidGlassTokens = typeof tokens;
`;
out('implementations/react/src/tokens.ts', ts);
out('implementations/react-native/src/tokens.ts', ts);

// ---------- Swift ----------
const swift = `// GENERATED by build-tokens.mjs from tokens.json — do not edit by hand.
// Numeric values are project estimates, not Apple values.
import CoreGraphics

public enum LGTokens {
    public enum Radius {
${Object.entries(t.radius).map(([k, v]) => `        public static let ${k}: CGFloat = ${v}`).join('\n')}
    }
    public enum Spacing {
${Object.entries(t.spacing).map(([k, v]) => `        public static let ${k}: CGFloat = ${v}`).join('\n')}
    }
    public enum Size {
${Object.entries(t.size).map(([k, v]) => `        public static let ${k}: CGFloat = ${v}`).join('\n')}
    }
    public enum Motion {
        public static let pressScale: CGFloat = ${t.motion.pressScale}
        public static let durationFast: Double = ${t.motion.durationFast / 1000}
        public static let durationBase: Double = ${t.motion.durationBase / 1000}
        public static let durationSlow: Double = ${t.motion.durationSlow / 1000}
    }
    /// HIG: dark dimming layer of 35% opacity behind clear glass over bright content (E-06).
    public static let clearDimmingOpacity: Double = 0.35
    public static let containerSpacing: CGFloat = ${t.spacing.xl}
}
`;
out('implementations/swiftui/Sources/LiquidGlassKit/LGTokens.swift', swift);
